/* Демо 8. Строка формата и аргументы.
 *
 * Заход первый — сборка без предупреждений:
 *
 *   gcc -std=c11 08-printf-lie.c -o lie && ./lie
 *
 * Заход второй ничего не запускает, он нужен ради того, что скажет
 * компилятор:
 *
 *   gcc -std=c11 -Wall -Wextra 08-printf-lie.c -o lie
 *
 * В программе четыре строки, помеченные словом «ложь». До запуска скажите про
 * каждую, что именно в ней не сходится и чем это кончится.
 *
 * Остальные вопросы — в README.md.
 */
#include <stdio.h>

int main(void)
{
    long long big = 5000000000LL;
    double    d   = 3.5;
    int       n   = 42;

    printf("сказали правду:\n");
    printf("  big = %lld\n", big);
    printf("  d   = %f\n", d);
    printf("  n   = %d\n", n);

    printf("\nсоврали:\n");
    printf("  %%d для long long: %d\n", big);   /* ложь 1 */
    printf("  %%d для double:    %d\n", d);     /* ложь 2 */
    printf("  два %%d, один арг: %d %d\n", n);  /* ложь 3 */
    fflush(stdout);   /* иначе строки выше потеряются, если программа упадёт */
    printf("  %%s для числа 42:  %s\n", n);     /* ложь 4 */

    return 0;
}
